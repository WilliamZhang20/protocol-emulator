"""Low-speed USB on the spatial fabric: packet transmit (NRZI, bit stuffing,
CRC16 and EOP generated by tiles) and packet receive with clock recovery,
destuffing and CRC16 residue checking."""

import random

import cocotb
from cocotb.triggers import ClockCycles, RisingEdge

from cocotb_tests.common import reset_top, start_clock, wait_until_halted
from cocotb_tests.fabric import (
    Bus, drain_rx, load_program, push_tx, select_channel, start_engine, stream_tx,
)
from cocotb_tests.line_codes import (
    J, K, SE0, USB_SYNC, crc16_usb, lsb_bits, usb_decode, usb_encode, usb_state,
)
from cocotb_tests.protocols import USB_DM, USB_DP, usb_ls_receive, usb_ls_transmit

BIT = 33            # 50 MHz / 1.5 Mb/s = 33.3 cycles (1% fast, inside spec)
PID_DATA0 = 0xC3


def data_packet(payload: bytes) -> bytes:
    return bytes([USB_SYNC, PID_DATA0]) + payload + crc16_usb(payload).to_bytes(2, "little")


def ends_in_stuffed_bit(payload: bytes) -> bool:
    """True if the last bit on the line before EOP is a stuffed 0 (the same
    stuffing rule as the reference encoder)."""
    ones, last_stuffed = 0, False
    for bit in lsb_bits(data_packet(payload)):
        ones = ones + 1 if bit else 0
        last_stuffed = ones == 6
        if last_stuffed:
            ones = 0
    return last_stuffed


def stuffed_at_eop_payload() -> bytes:
    rng = random.Random(0)
    while True:
        payload = bytes(rng.randrange(256) for _ in range(rng.randrange(1, 4)))
        if ends_in_stuffed_bit(payload):
            states = usb_encode(data_packet(payload))
            assert len(states) - 3 > 8 * len(data_packet(payload))   # stuffed
            return payload


TX_CASES = {
    "stuffing_mix": bytes([0x01, 0xFF, 0xFF, 0x80, 0x7E, 0x3F]),
    "empty": b"",
    "one_byte": b"\x00",
    "max_all_ones": bytes([0xFF] * 8),
    "max_random": random.Random(5).randbytes(8),
    "stuffed_bit_before_eop": stuffed_at_eop_payload(),
}


@cocotb.test()
@cocotb.parametrize(case=list(TX_CASES))
async def test_usb_ls_transmit_packet(dut, case):
    """Every transition on the bit grid; the decoded line equals SYNC, PID,
    payload and CRC16 with correct stuffing (data and CRC), then exactly
    two bits of SE0 and J. Cases cover an empty and a maximum (8-byte)
    payload, all-ones stuffing, and a stuffed bit as the last bit before
    EOP."""
    payload = TX_CASES[case]
    await start_clock(dut)
    await reset_top(dut)
    bus = Bus(dut)
    stream = bytes([USB_SYNC, PID_DATA0]) + payload
    await load_program(dut, usb_ls_transmit(BIT))
    for byte in stream[:4]:
        await push_tx(dut, byte)
    await start_engine(dut)
    feeder = cocotb.start_soon(stream_tx(dut, list(stream[4:])))

    trace = []  # (cycle, state) at every change
    cycle, last = 0, None
    while True:
        await RisingEdge(dut.clk)
        cycle += 1
        both = (1 << USB_DP) | (1 << USB_DM)
        driven = (int(dut.uio_oe.value) & both) == both
        state = usb_state(bus.level(USB_DP), bus.level(USB_DM)) if driven else None
        if state != last:
            trace.append((cycle, state))
            last = state
        if trace and trace[-1][1] is None and len(trace) > 3:
            break
        assert cycle < 200 * BIT * 10, "packet never finished"
    await feeder

    active = [(c, s) for c, s in trace if s is not None]
    start = next(c for c, s in active if s == K)
    for c, _ in active:
        if c > start:
            assert (c - start) % BIT == 0, f"transition off the bit grid at {c - start}"
    end = trace[-1][0]
    samples = []
    for i in range((end - start) // BIT):
        t = start + i * BIT + BIT // 2
        samples.append([s for c, s in active if c <= t][-1])
    packet, se0_bits = usb_decode(samples)
    assert packet == data_packet(payload), packet.hex()
    assert se0_bits == 2


async def drive_usb(dut, bus: Bus, states: list[str], bit: int, jitter: int = 0,
                    seed: int = 0) -> None:
    """Drive line states, each bit lasting `bit` cycles plus a random
    -jitter..+jitter cycles."""
    levels = {J: (0, 1), K: (1, 0), SE0: (0, 0)}
    rng = random.Random(seed)
    for state in states:
        bus.drive[USB_DP], bus.drive[USB_DM] = levels[state]
        await ClockCycles(dut.clk, bit + rng.randint(-jitter, jitter))
    bus.drive[USB_DP], bus.drive[USB_DM] = levels[J]


async def run_receive(dut, packet: bytes, sender_bit: int, jitter: int = 0) -> list[int]:
    await start_clock(dut)
    await reset_top(dut)
    bus = Bus(dut)
    bus.drive[USB_DP], bus.drive[USB_DM] = 0, 1      # idle J
    await load_program(dut, usb_ls_receive(BIT))
    await select_channel(dut, 1)                 # shifter 1's channel
    await start_engine(dut)
    await ClockCycles(dut.clk, 1500)
    sender = cocotb.start_soon(drive_usb(dut, bus, usb_encode(packet), sender_bit, jitter))
    received = await drain_rx(dut, len(packet) + 1)
    await sender
    await wait_until_halted(dut)
    return received


@cocotb.test()
async def test_usb_ls_receive_with_clock_recovery(dut):
    """The sender runs 3% slow; resync on every transition keeps sampling
    mid-bit. Stuffed bits are dropped and the CRC16 residue checks."""
    payload = bytes([0xFF, 0xFF, 0x00, 0x5A, 0xFC])
    packet = data_packet(payload)
    received = await run_receive(dut, packet, sender_bit=BIT + 1)
    assert bytes(received[:-1]) == packet, bytes(received).hex()
    assert received[-1] == 0xA5, "CRC16 residue should check"


@cocotb.test()
async def test_usb_ls_receive_detects_bad_crc(dut):
    payload = bytes([0x12, 0x34])
    packet = bytearray(data_packet(payload))
    packet[-1] ^= 0x40
    received = await run_receive(dut, bytes(packet), sender_bit=BIT)
    assert bytes(received[:-1]) == bytes(packet)
    assert received[-1] == 0xEE, "corrupted CRC must be flagged"


RX_CASES = {
    "fast_3pct": (bytes([0xFF, 0xFF, 0x00, 0x5A, 0xFC]), BIT - 1, 0),
    "max_all_ones": (bytes([0xFF] * 8), BIT, 0),
    "empty": (b"", BIT, 0),
    "random_jitter": (random.Random(6).randbytes(8), BIT, 1),
    "stuffed_bit_before_eop": (stuffed_at_eop_payload(), BIT + 1, 0),
}


@cocotb.test()
@cocotb.parametrize(case=list(RX_CASES))
async def test_usb_ls_receive_cases(dut, case):
    """Clock recovery and destuffing across sender rates (3% fast), random
    per-bit jitter of one cycle, maximum stuffing, an empty data packet and
    a stuffed bit right before EOP; the CRC16 verdict must be good."""
    payload, sender_bit, jitter = RX_CASES[case]
    packet = data_packet(payload)
    received = await run_receive(dut, packet, sender_bit, jitter)
    assert bytes(received[:-1]) == packet, bytes(received).hex()
    assert received[-1] == 0xA5, "CRC16 residue should check"



@cocotb.test()
async def test_usb_ls_receive_overrun_is_not_success(dut):
    """A correct wire CRC must not hide bytes lost to host backpressure.

    Hold off host reads until an eight-byte payload and its CRC have arrived.
    The stream's four FIFO slots plus two byte-tile slots and one pending
    shifter byte cannot retain the entire raw packet. The result must be bad,
    even though the independent bit-level CRC checker sees a valid packet.
    """
    from cocotb_tests.fabric import drain_until_halted

    await start_clock(dut)
    await reset_top(dut)
    bus = Bus(dut)
    bus.drive[USB_DP], bus.drive[USB_DM] = 0, 1
    packet = data_packet(bytes(range(8)))
    await load_program(dut, usb_ls_receive(BIT))
    await select_channel(dut, 1)
    await start_engine(dut)
    await ClockCycles(dut.clk, 1500)
    await drive_usb(dut, bus, usb_encode(packet), BIT)
    await ClockCycles(dut.clk, BIT * 2)
    received = await drain_until_halted(dut)
    assert len(received) < len(packet) + 1, "fixture did not exercise receive overrun"
    assert received[-1] == 0xEE, "valid CRC incorrectly reported success after FIFO data loss"
