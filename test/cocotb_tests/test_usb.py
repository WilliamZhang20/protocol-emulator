"""Low-speed USB on the spatial fabric: packet transmit (NRZI, bit stuffing,
CRC16 and EOP generated by tiles) and packet receive with clock recovery,
destuffing and CRC16 residue checking."""

import cocotb
from cocotb.triggers import ClockCycles, RisingEdge

from cocotb_tests.common import reset_top, start_clock, wait_until_halted
from cocotb_tests.fabric import Bus, drain_rx, load_program, push_tx, start_engine, stream_tx
from cocotb_tests.line_codes import (
    J, K, SE0, USB_SYNC, crc16_usb, usb_decode, usb_encode, usb_state,
)
from cocotb_tests.protocols import USB_DM, USB_DP, usb_ls_receive, usb_ls_transmit

BIT = 33            # 50 MHz / 1.5 Mb/s = 33.3 cycles (1% fast, inside spec)
PID_DATA0 = 0xC3


def data_packet(payload: bytes) -> bytes:
    return bytes([USB_SYNC, PID_DATA0]) + payload + crc16_usb(payload).to_bytes(2, "little")


@cocotb.test()
async def test_usb_ls_transmit_packet(dut):
    """Payload includes 0xFF runs so stuffing is exercised in data and CRC."""
    await start_clock(dut)
    await reset_top(dut)
    bus = Bus(dut)
    payload = bytes([0x01, 0xFF, 0xFF, 0x80, 0x7E, 0x3F])
    stream = bytes([USB_SYNC, PID_DATA0]) + payload
    await load_program(dut, usb_ls_transmit(BIT))
    for byte in stream[:4]:
        await push_tx(dut, byte)
    await start_engine(dut)
    feeder = cocotb.start_soon(stream_tx(dut, list(stream[4:])))

    trace = []  # (cycle, state) at every change
    cycle, last = 0, None
    while True:
        await RisingEdge(dut.clk)
        cycle += 1
        both = (1 << USB_DP) | (1 << USB_DM)
        driven = (int(dut.uio_oe.value) & both) == both
        state = usb_state(bus.level(USB_DP), bus.level(USB_DM)) if driven else None
        if state != last:
            trace.append((cycle, state))
            last = state
        if trace and trace[-1][1] is None and len(trace) > 3:
            break
        assert cycle < 200 * BIT * 10, "packet never finished"
    await feeder

    active = [(c, s) for c, s in trace if s is not None]
    start = next(c for c, s in active if s == K)
    for c, _ in active:
        if c > start:
            assert (c - start) % BIT == 0, f"transition off the bit grid at {c - start}"
    end = trace[-1][0]
    samples = []
    for i in range((end - start) // BIT):
        t = start + i * BIT + BIT // 2
        samples.append([s for c, s in active if c <= t][-1])
    packet, se0_bits = usb_decode(samples)
    assert packet == data_packet(payload), packet.hex()
    assert se0_bits == 2


async def drive_usb(dut, bus: Bus, states: list[str], bit: int) -> None:
    levels = {J: (0, 1), K: (1, 0), SE0: (0, 0)}
    for state in states:
        bus.drive[USB_DP], bus.drive[USB_DM] = levels[state]
        await ClockCycles(dut.clk, bit)
    bus.drive[USB_DP], bus.drive[USB_DM] = levels[J]


async def run_receive(dut, packet: bytes, sender_bit: int) -> list[int]:
    await start_clock(dut)
    await reset_top(dut)
    bus = Bus(dut)
    bus.drive[USB_DP], bus.drive[USB_DM] = 0, 1      # idle J
    await load_program(dut, usb_ls_receive(BIT))
    await start_engine(dut)
    await ClockCycles(dut.clk, 1500)
    sender = cocotb.start_soon(drive_usb(dut, bus, usb_encode(packet), sender_bit))
    received = await drain_rx(dut, len(packet) + 1)
    await sender
    await wait_until_halted(dut)
    return received


@cocotb.test()
async def test_usb_ls_receive_with_clock_recovery(dut):
    """The sender runs 3% slow; resync on every transition keeps sampling
    mid-bit. Stuffed bits are dropped and the CRC16 residue checks."""
    payload = bytes([0xFF, 0xFF, 0x00, 0x5A, 0xFC])
    packet = data_packet(payload)
    received = await run_receive(dut, packet, sender_bit=BIT + 1)
    assert bytes(received[:-1]) == packet, bytes(received).hex()
    assert received[-1] == 0xA5, "CRC16 residue should check"


@cocotb.test()
async def test_usb_ls_receive_detects_bad_crc(dut):
    payload = bytes([0x12, 0x34])
    packet = bytearray(data_packet(payload))
    packet[-1] ^= 0x40
    received = await run_receive(dut, bytes(packet), sender_bit=BIT)
    assert bytes(received[:-1]) == bytes(packet)
    assert received[-1] == 0xEE, "corrupted CRC must be flagged"
